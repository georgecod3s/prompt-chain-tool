import Link from "next/link";
import { notFound } from "next/navigation";
import { requireAdmin } from "@/lib/admin";
import { loadRuns } from "@/lib/runs";
import type { Chain } from "@/lib/types";
import Flash from "@/components/Flash";
import RunCard from "@/components/RunCard";
import SubmitButton from "@/components/SubmitButton";
import { deleteMedia } from "../../../actions";

export const dynamic = "force-dynamic";

export default async function ChainMedia({ params, searchParams }: PageProps<"/chains/[id]/media">) {
    const { id } = await params;
    const sp = await searchParams;
    const status = typeof sp.status === "string" ? sp.status : "";
    const { supabase } = await requireAdmin();
    const { data: chain } = await supabase.from("prompt_chains").select("*").eq("id", id).maybeSingle<Chain>();
    if (!chain) notFound();

    const { runs, error } = await loadRuns(supabase, { chainId: id });
    const shown = runs.filter((r) => !status || r.run.status === status);
    const done = runs.filter((r) => r.run.status === "completed");
    const totalCaps = done.reduce((s, r) => s + r.captions.length, 0);

    return (
        <div className="space-y-6">
            <Link href={`/chains/${chain.id}`} className="text-sm text-muted hover:text-fg">← Back to {chain.name}</Link>
            <Flash ok={sp.ok} error={sp.error} />
            <header className="flex flex-wrap items-end justify-between gap-4">
                <div>
                    <p className="text-xs font-semibold uppercase tracking-wider text-accent">Generated media</p>
                    <h1 className="text-3xl font-bold">{chain.name}</h1>
                    <p className="mt-1 text-sm text-muted">
                        {runs.length} runs · {done.length} completed · {runs.length - done.length} failed/running · {totalCaps} captions
                    </p>
                </div>
                <form className="flex gap-2">
                    <select name="status" defaultValue={status} className="input !w-auto">
                        <option value="">All runs</option>
                        <option value="completed">Completed</option>
                        <option value="failed">Failed</option>
                    </select>
                    <button className="btn btn-ghost">Filter</button>
                </form>
            </header>
            {error && <p className="card p-4 text-sm text-danger">{error.message}</p>}

            <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
                {shown.map(({ run, image, captions }) => (
                    <RunCard key={run.id} run={run} imageUrl={image?.image_url} captions={captions}>
                        {image && (
                            <form action={deleteMedia} className="ml-auto">
                                <input type="hidden" name="image_id" value={image.id} />
                                <input type="hidden" name="chain_id" value={chain.id} />
                                <SubmitButton className="text-xs font-semibold text-danger hover:underline" pending="…" confirm="Delete this photo and all of its captions?">
                                    Delete
                                </SubmitButton>
                            </form>
                        )}
                    </RunCard>
                ))}
            </div>
            {!shown.length && (
                <div className="card p-8 text-center text-sm text-muted">
                    Nothing generated by this chain yet.{" "}
                    <Link href={`/chains/${chain.id}#generate`} className="font-semibold text-accent hover:underline">Run it on a photo →</Link>
                </div>
            )}
        </div>
    );
}
